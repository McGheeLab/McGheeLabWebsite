#!/usr/bin/env python3
"""
gen_simulations.py — one standalone HTML per simulation, numbered the way
the whiteboard addresses them (V3.737).

For every class folder in modules/manifest.json, for every WEEKLY module
file named `NN-…html` (the number is the module number), for every section
heading `h2[data-nav="T.S"]` whose block contains a <canvas>, write

    modules/<class>/simulations/N.T.S.html

a small standalone page that opens the module with `?embed=T.S&sim=1` —
the simulation part of that section only (scenario bar, controls,
canvases), exactly as the module renders it. The module stays the single
source of truth: nothing is copied, so a fix to a lesson fixes its
simulation file too. Also writes `simulations/index.json` listing every
simulation (ref, file, module, titles) for the whiteboard resolver.

Run from the repo root after adding or renumbering a module:

    python3 scripts/gen_simulations.py            # all classes
    python3 scripts/gen_simulations.py bme466     # one class
    python3 scripts/gen_simulations.py --check    # exit 1 if files are stale

Homework (`hw-…`), notes (`w01-…`, `R1-…`) and anything without a numeric
prefix are skipped: only lessons have whiteboard numbers.
"""
import json, os, re, sys, html

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES = os.path.join(ROOT, 'modules')

H2_RE = re.compile(r'<h2[^>]*data-nav="(\d+)\.(\d+)"[^>]*>', re.I)
TITLE_ATTR_RE = re.compile(r'data-title="([^"]*)"')
PAGE_TITLE_RE = re.compile(r'<title>([^<]*)</title>', re.I)
MODULE_FILE_RE = re.compile(r'^(\d+)[a-z]?-.*\.html$')  # 04c-… is still module 4 (V3.774)

WRAPPER = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<!-- GENERATED by scripts/gen_simulations.py — do not edit. Whiteboard ref {ref}.
     This page shows ONE simulation from {module_file}: the module itself is
     the source; regenerate after changing it. -->
<style>
  html,body{{margin:0;height:100%;background:#fff;font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif}}
  .sim-bar{{display:flex;align-items:center;gap:10px;height:34px;padding:0 12px;background:#0f172a;color:#e2e8f0;font-size:.8rem}}
  .sim-bar b{{color:#f59e0b;font-weight:700}}
  .sim-bar a{{color:#93c5fd;margin-left:auto;text-decoration:none}}
  .sim-bar a:hover{{text-decoration:underline}}
  iframe{{display:block;width:100%;height:calc(100% - 34px);border:0}}
</style>
</head>
<body>
<div class="sim-bar"><b>{ref}</b> <span>{section_title}</span> <span style="opacity:.6">· {module_title}</span>
  <a href="../{module_file}#tab-{tab_anchor}" title="Open the full lesson">Open in the module →</a></div>
<iframe src="../{module_file}?embed={tab}.{sec}&sim=1" title="{title}" allow="fullscreen"></iframe>
</body>
</html>
"""


def sections_with_canvas(src):
    heads = [(m.start(), int(m.group(1)), int(m.group(2)), m.group(0)) for m in H2_RE.finditer(src)]
    out = []
    for i, (pos, tab, sec, tag) in enumerate(heads):
        end = heads[i + 1][0] if i + 1 < len(heads) else len(src)
        seg = src[pos:end]
        if '<canvas' not in seg:
            continue
        m = TITLE_ATTR_RE.search(tag)
        title = html.unescape(m.group(1)) if m else f'{tab}.{sec}'
        # the tab anchor: the enclosing <section id="tab-…"> — search backwards
        sec_open = [x for x in re.finditer(r'<section id="tab-([^"]+)"', src[:pos])]
        tab_anchor = sec_open[-1].group(1) if sec_open else ''
        out.append({'tab': tab, 'sec': sec, 'title': title, 'tabAnchor': tab_anchor})
    return out


def generate(class_id, files, check=False):
    folder = os.path.join(MODULES, class_id)
    sims_dir = os.path.join(folder, 'simulations')
    index, wanted, stale = [], set(), []
    claimed = {}
    for f in files:
        m = MODULE_FILE_RE.match(f['name'])
        if not m:
            continue
        n = int(m.group(1))
        path = os.path.join(folder, f['name'])
        if not os.path.exists(path):
            continue
        # V3.774 — a letter suffix (04c-…) keeps the module number, so two files can
        # now claim the same one. Refuse rather than silently overwrite each other.
        if n in claimed:
            sys.exit(f'ERROR {class_id}: modules {claimed[n]} and {f["name"]} both claim '
                     f'module {n} — the {n}.T.S refs would collide. Rename or drop one.')
        claimed[n] = f['name']
        src = open(path, encoding='utf-8').read()
        if 'whiteboard-panel.js' not in src:
            continue  # cannot embed
        mt = PAGE_TITLE_RE.search(src)
        module_title = html.unescape(mt.group(1)) if mt else f['name']
        module_title = re.sub(r'\s*\(.*$', '', module_title).strip()
        for s_ in sections_with_canvas(src):
            ref = f"{n}.{s_['tab']}.{s_['sec']}"
            fname = f'{ref}.html'
            wanted.add(fname)
            content = WRAPPER.format(
                title=html.escape(f"{ref} · {s_['title']} — {module_title}"), ref=ref,
                module_file=html.escape(f['name']), module_title=html.escape(module_title),
                section_title=html.escape(s_['title']), tab=s_['tab'], sec=s_['sec'],
                tab_anchor=html.escape(s_['tabAnchor']))
            index.append({'ref': ref, 'file': fname, 'module': n, 'moduleFile': f['name'],
                          'moduleTitle': module_title, 'tab': s_['tab'], 'section': s_['sec'],
                          'title': s_['title']})
            out = os.path.join(sims_dir, fname)
            if check:
                if not os.path.exists(out) or open(out, encoding='utf-8').read() != content:
                    stale.append(fname)
            else:
                os.makedirs(sims_dir, exist_ok=True)
                with open(out, 'w', encoding='utf-8') as fh:
                    fh.write(content)
    if not index:
        return 0, stale
    index.sort(key=lambda r: (r['module'], r['tab'], r['section']))
    idx_path = os.path.join(sims_dir, 'index.json')
    idx_content = json.dumps({'class': class_id, 'generated': 'scripts/gen_simulations.py', 'simulations': index},
                             indent=1, ensure_ascii=False) + '\n'
    if check:
        if not os.path.exists(idx_path) or open(idx_path, encoding='utf-8').read() != idx_content:
            stale.append('index.json')
        # files no longer wanted
        if os.path.isdir(sims_dir):
            for existing in os.listdir(sims_dir):
                if existing.endswith('.html') and existing not in wanted:
                    stale.append(existing + ' (orphan)')
    else:
        with open(idx_path, 'w', encoding='utf-8') as fh:
            fh.write(idx_content)
        for existing in os.listdir(sims_dir):
            if existing.endswith('.html') and existing not in wanted:
                os.remove(os.path.join(sims_dir, existing))
                print(f'  removed orphan {class_id}/simulations/{existing}')
    return len(index), stale


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    check = '--check' in sys.argv
    manifest = json.load(open(os.path.join(MODULES, 'manifest.json'), encoding='utf-8'))
    total, all_stale = 0, []
    for class_id, info in manifest.get('folders', {}).items():
        if args and class_id not in args:
            continue
        n, stale = generate(class_id, info.get('files', []), check=check)
        if n:
            print(f'{class_id}: {n} simulations' + (f' — {len(stale)} stale' if stale else ''))
        total += n
        all_stale += [f'{class_id}/simulations/{s}' for s in stale]
    if check:
        if all_stale:
            print('STALE:\n  ' + '\n  '.join(all_stale))
            sys.exit(1)
        print(f'ok — {total} simulation files up to date')
    else:
        print(f'wrote {total} simulation files')


if __name__ == '__main__':
    main()
