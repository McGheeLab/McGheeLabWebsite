/* grant-export-tex.js — V3.179.
 *
 * LaTeX export for a grant draft. Walks the section/block tree and emits
 * a single .tex source file the user can paste into Overleaf or compile
 * locally. Reasonable defaults — no agency-specific class file (deferred
 * to V3.183+).
 *
 * Public API: window.GRANT_EXPORT_TEX.runExport(doc, tree)
 */

(function () {
  'use strict';

  function escTex(s) {
    if (s == null) return '';
    return String(s)
      .replace(/\\/g, '\\textbackslash{}')
      .replace(/([&%$#_{}])/g, '\\$1')
      .replace(/~/g, '\\textasciitilde{}')
      .replace(/\^/g, '\\textasciicircum{}')
      .replace(/</g, '\\textless{}')
      .replace(/>/g, '\\textgreater{}');
  }

  /* Strip HTML tags from a contenteditable body before LaTeX-escaping. */
  function htmlToText(html) {
    if (!html) return '';
    var tmp = document.createElement('div');
    tmp.innerHTML = html;
    return tmp.textContent || tmp.innerText || '';
  }

  function paragraphToTex(blk) {
    return escTex(htmlToText(blk.body)).trim() + '\n';
  }

  function aimBulletsToTex(blk) {
    var attrs = blk.attrs || {};
    var parts = [];
    if (attrs.hypothesis) {
      parts.push('\\textbf{Hypothesis.} ' + escTex(attrs.hypothesis));
    }
    var aims = Array.isArray(attrs.aims) ? attrs.aims : [];
    if (aims.length) {
      parts.push('\\begin{itemize}');
      aims.forEach(function (aim) {
        var line = '\\item \\textbf{' + escTex(aim.title || 'Aim') + '.}';
        if (aim.summary) line += ' ' + escTex(aim.summary);
        parts.push(line);
      });
      parts.push('\\end{itemize}');
    }
    return parts.join('\n') + '\n';
  }

  function budgetTableToTex(blk, doc) {
    var summary = (doc && doc.budgetSummary) || { directs: 0, indirects: 0, total: 0, years: [] };
    var lines = ['\\begin{tabular}{lrrr}', '\\hline', 'Year & Directs & Indirects & Total \\\\', '\\hline'];
    (summary.years || []).forEach(function (y) {
      lines.push(escTex(y.year) + ' & \\$' + numFmt(y.directs) + ' & \\$' + numFmt(y.indirects) + ' & \\$' + numFmt(y.total) + ' \\\\');
    });
    lines.push('\\hline');
    lines.push('\\textbf{Total} & \\$' + numFmt(summary.directs) + ' & \\$' + numFmt(summary.indirects) + ' & \\$' + numFmt(summary.total) + ' \\\\');
    lines.push('\\hline');
    lines.push('\\end{tabular}');
    return lines.join('\n') + '\n';
  }

  function personnelTableToTex(blk) {
    var rows = (blk.attrs && blk.attrs.rows) || [];
    if (!rows.length) return '\\textit{(no personnel rows)}\n';
    var lines = ['\\begin{tabular}{lllp{4cm}}', '\\hline', 'Name & Role & Effort & Notes \\\\', '\\hline'];
    rows.forEach(function (r) {
      lines.push(escTex(r.name || '') + ' & ' + escTex(r.role || '') + ' & ' + escTex(r.effort || '') + ' & ' + escTex(r.notes || '') + ' \\\\');
    });
    lines.push('\\hline');
    lines.push('\\end{tabular}');
    return lines.join('\n') + '\n';
  }

  function complianceRowToTex(blk) {
    var answer = blk.attrs && blk.attrs.answer ? blk.attrs.answer : '(unanswered)';
    return '\\textbf{Q:} ' + escTex(blk.body || '') + '\\\\\n\\textbf{A:} ' + escTex(answer.toUpperCase()) + '\n';
  }

  function letterCardToTex(blk) {
    var a = blk.attrs || {};
    return '\\textbf{Letter from } ' + escTex(a.from || '(name)') +
           ', ' + escTex(a.role || '') + ', ' + escTex(a.institution || '') +
           '. \\textit{(letter attached separately)}\n';
  }

  function blockToTex(blk, doc) {
    switch (blk.kind) {
      case 'paragraph':       return paragraphToTex(blk);
      case 'aim-bullets':     return aimBulletsToTex(blk);
      case 'budget-table':    return budgetTableToTex(blk, doc);
      case 'personnel-table': return personnelTableToTex(blk);
      case 'compliance-row':  return complianceRowToTex(blk);
      case 'letter-card':     return letterCardToTex(blk);
      default:                return '\\textit{(unsupported block kind: ' + escTex(blk.kind) + ')}\n';
    }
  }

  function sectionToTex(sec, doc) {
    var out = '\n\\section*{' + escTex(sec.label || sec.kind) + '}\n';
    (sec.children || []).forEach(function (b) {
      out += blockToTex(b, doc) + '\n';
    });
    return out;
  }

  function preamble(doc) {
    var titleEsc = escTex(doc.title || 'Untitled Grant');
    return ''
      + '% Auto-generated by McGhee Lab RM grant writer (V3.179).\n'
      + '% Mechanism: ' + escTex(doc.mechanism || '') + ' | Agency: ' + escTex(doc.agency || '') + '\n'
      + '% Deadline: ' + escTex(doc.deadlineISO || 'TBD') + '\n'
      + '\\documentclass[11pt]{article}\n'
      + '\\usepackage[letterpaper, margin=0.5in]{geometry}\n'
      + '\\usepackage{helvet}\n'
      + '\\renewcommand{\\familydefault}{\\sfdefault}\n'
      + '\\usepackage{graphicx}\n'
      + '\\usepackage{amsmath}\n'
      + '\\usepackage{enumitem}\n'
      + '\\usepackage{titlesec}\n'
      + '\\titleformat{\\section}{\\normalsize\\bfseries}{\\thesection}{1em}{}\n'
      + '\\setlength{\\parindent}{0pt}\n'
      + '\\setlength{\\parskip}{6pt}\n'
      + '\\title{' + titleEsc + '}\n'
      + '\\author{}\n'
      + '\\date{}\n'
      + '\\begin{document}\n'
      + '\\begin{center}\\Large\\textbf{' + titleEsc + '}\\end{center}\n';
  }

  function build(doc, tree) {
    var out = preamble(doc);
    (tree.sections || []).forEach(function (sec) {
      out += sectionToTex(sec, doc);
    });
    out += '\n\\end{document}\n';
    return out;
  }

  function numFmt(n) { return (Number(n) || 0).toLocaleString('en-US', { maximumFractionDigits: 0 }); }

  function safeName(s) {
    return String(s || 'grant').replace(/[^\w\-]+/g, '_').replace(/^_+|_+$/g, '');
  }

  function downloadString(filename, content, mime) {
    var blob = new Blob([content], { type: mime || 'text/plain' });
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    setTimeout(function () { document.body.removeChild(a); URL.revokeObjectURL(url); }, 200);
  }

  function runExport(doc, tree) {
    var tex = build(doc, tree);
    downloadString(safeName(doc.title) + '.tex', tex, 'application/x-tex');
  }

  window.GRANT_EXPORT_TEX = {
    runExport: runExport,
    build: build,
    sectionToTex: sectionToTex,
    blockToTex: blockToTex,
  };
})();
